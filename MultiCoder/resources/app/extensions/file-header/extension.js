const path = require('node:path');
const vscode = require('vscode');

function activate(context) {
  context.subscriptions.push(
    vscode.commands.registerCommand('fileHeader.insert', async () => {
      const document = vscode.window.activeTextDocument;
      if (!document) {
        await vscode.window.showWarningMessage('Open a file before inserting a header.');
        return;
      }

      const baseName = path.basename(document.fileName);
      const isMarkdown = /\.(md|markdown)$/i.test(baseName);
      const text = document.getText();

      if (/^\s*(\/\/|#|<!--)/.test(text)) {
        await vscode.window.showInformationMessage(`${baseName} already starts with a comment.`);
        return;
      }

      const stamp = new Date().toISOString().slice(0, 10);
      const header = isMarkdown
        ? `<!-- @file ${baseName} · generated with MultiCoder on ${stamp} -->\n\n`
        : `// @file ${baseName}\n// @generated by MultiCoder on ${stamp}\n\n`;

      await vscode.workspace.fs.writeFile(document.uri, Buffer.from(header + text, 'utf8'));
      await vscode.window.showInformationMessage(`Inserted a header into ${baseName}.`);
    }),
  );
}

function deactivate() {}

module.exports = { activate, deactivate };
